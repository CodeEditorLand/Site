/**
 * Reference - generate `Documentation/Component-Reference.md` from the tree.
 *
 * ─── WHY A GENERATOR, AND NOT A FILE SOMEONE WRITES ───────────────────────
 * The reference is the document a contributor reads before touching a
 * component, and the one thing such a document must never do is disagree with
 * the code it describes. So it is not written: `Source/Content/Specimen/
 * Reference.ts` reads the ten family modules - their rows, their columns, their
 * `MatrixCell`, their specimens, their improvements - and this script prints
 * that model as markdown. A component added to a family moves the document's
 * figures, its slot tables, its matrix and its prohibition numbering in the same
 * edit, because there is nothing here to keep in step by hand.
 *
 * ─── HOW IT RUNS WITHOUT A SITE BUILD ─────────────────────────────────────
 * The family modules are TypeScript with `.js` specifiers, which Node cannot
 * import directly. So the model is bundled with the `esbuild` the site already
 * depends on, imported from a `data:` URL, and printed. No Astro, no Vite, no
 * build, no test - and nothing is written to the tree but the one file.
 *
 *   node Maintain/Script/Reference.mjs
 *
 * ─── THE RULE THE OUTPUT KEEPS ────────────────────────────────────────────
 * Nothing is shortened. A prohibition prints in full, a `found`/`built` pair
 * prints in full, and every `N/A` cell in a matrix resolves to a numbered
 * sentence printed under it. A reference that trimmed its reasons to fit a table
 * would be a second, quieter opinion about the components.
 */
import { mkdir, writeFile } from "node:fs/promises";

import { fileURLToPath } from "node:url";

import { dirname, resolve } from "node:path";

import { build } from "esbuild";

/** The site's root: this file lives at `Maintain/Script/`, two levels down. */
const Root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

/** Where the document is written. */
const Target = resolve(Root, "Documentation/Component-Reference.md");

/**
 * Bundle one module of the tree and import it.
 *
 * `stdin` is the entry so the specifier resolves against the specimen directory
 * exactly as Vite resolves it; `platform: "node"` keeps the bundle free of
 * browser shims, and `write: false` keeps it in memory - the only file this
 * script touches is the document.
 */
const Load = async (Name) => {
	const Result = await build({
		stdin: {
			contents: `export * from "./${Name}.js";`,
			resolveDir: resolve(Root, "Source/Content/Specimen"),
			loader: "ts",
		},
		bundle: true,
		format: "esm",
		platform: "node",
		write: false,
		logLevel: "silent",
	});

	const Code = Result.outputFiles[0].text;

	return import(
		`data:text/javascript;base64,${Buffer.from(Code).toString("base64")}`
	);
};

const Reference = await Load("Reference");

const Gallery = await Load("Gallery");

/* ─── MARKDOWN, KEPT HONEST ──────────────────────────────────────────────── */

/**
 * Escape the two characters that would change a markdown document's meaning.
 *
 * The families' reasons quote markup - `<details>`, `<dl>`, `<iframe>` - and a
 * raw `<details>` in a paragraph is an HTML block to every markdown renderer.
 * The angle brackets are escaped rather than the sentences rewritten: a reason
 * is the family's own words, and quoting a component's element is what makes it
 * checkable.
 */
const Text = (Value) =>
	String(Value).replaceAll("<", "&lt;").replaceAll(">", "&gt;");

/** A table cell: the pipe is the table's own separator and has to be escaped. */
const Cell = (Value) => Text(Value).replaceAll("|", "\\|");

/** A fenced code span, for a path or a prop. */
const Code = (Value) => `\`${String(Value).replaceAll("`", "ˋ")}\``;

/** `▪` / `N/A(n)` / `—`, the matrix's three marks. */
const Mark = (Value) => {
	if (Value.disposition === "built") return "▪";

	if (Value.disposition === "na")
		return Value.law === undefined ? "N/A" : `N/A(${Value.law})`;

	return "—";
};

/** A markdown table from a head and rows. */
const Table = (Head, Rows) => {
	const Lines = [
		`| ${Head.map(Cell).join(" | ")} |`,
		`| ${Head.map(() => "---").join(" | ")} |`,
		...Rows.map((Row) => `| ${Row.map(Cell).join(" | ")} |`),
	];

	return Lines.join("\n");
};

/** A blockquote-free paragraph at the document's caption weight. */
const Line = (Label, Value) => `**${Label}.** ${Text(Value)}`;

/* ─── THE DOCUMENT ───────────────────────────────────────────────────────── */

const Out = [];

Out.push(`# The component reference

<!-- Generated by \`Maintain/Script/Reference.mjs\` from \`Source/Content/Specimen/*.ts\`.
     Do not edit by hand: an edit here is a second opinion about a component, and
     the next regeneration would delete it. Change the family module, then run
     the script. -->

This is the document a contributor reads before touching a component. It states,
for each of the ${Reference.EntryCount} families of the document, the same five
things in the same order:

1. **what the family is for** - the sentence its band argues, and what it is read for;
2. **its slots** - the parts a page may mount, each with the file it lives in;
3. **what it is asked** - the states it is conditioned on, and the shapes and
   contexts it is composed at, with the figure each column is built by;
4. **what it may never be** - the sentences the family's own matrix uses to mark
   a combination impossible, collected rather than written;
5. **the row that proves it** - one live specimen that shows the family
   surviving the case its own subject says it is worst at.

Every figure, every column, every prohibition and every matrix cell is read from
the ten family modules (\`Source/Content/Specimen/<Family>.ts\`), which are the
same tables \`/Specimen\` and \`/Specimen/States\` read. Nothing here is a second
claim about a component: a cell in this document and a cell on the family's
matrix are the same cell, read twice.

**How to use it.** Find the family, read *what it is for* and *what it may never
be* before you open a file. If you are adding a combination, check the matrix
first: if the cell is \`N/A\`, the family has already written the sentence saying
why, and the sentence is the argument you would have to beat. If the cell is
\`▪\`, the combination renders and there is a live row for it on
\`/Specimen/States\`. If the condition is not on the family's matrix at all, the
entry's *what its matrix does not ask* names the hole.

---

## The contract - what a block may be, and may never be

These ${Reference.Contract.length} laws hold before any family's own matrix is
read. They are the only prose in this document that is not derived: they are the
document's constitution (\`DESIGN-COMPLETE.md\` §4.2 and §4.4), restated as a
table because a contributor reads a table and skips a paragraph. A law with no
check is a preference, so each one names what a reviewer looks at.

${Table(
	["#", "LAW", "MEANS", "CHECK", "SOURCE"],
	Reference.Contract.map((Law, Position) => [
		String(Position + 1).padStart(2, "0"),
		Law.law,
		Law.means,
		Law.check,
		Law.source,
	]),
)}

---

## The spine - the ${Gallery.ConditionCount} conditions every family is measured against

The families ask their own questions; the states gallery folds those question
sets onto one spine so that two families can be compared at all. This is that
spine, with the figure every component of the document contributes. \`UNASKED\`
is the third disposition: a condition no family's matrix has a column for, and
therefore a hole rather than a failure.

${Table(
	["CONDITION", "ASKS", "GROUP", "STATUS WORD", "BUILT", "N/A", "UNASKED"],
	Gallery.ConditionRows.map((Row) => [
		Row.condition.label,
		Row.condition.ask,
		Row.condition.group,
		Row.condition.status ?? "—",
		String(Row.built),
		String(Row.reasons),
		String(Row.unasked),
	]),
)}

The spine holds ${Reference.SpineCells} cells across ${Reference.SlotCount}
components; ${Reference.SpineBuilt} are built and ${Reference.SpineUnasked} are
unasked. The families' own matrices hold ${Reference.MatrixCells} cells between
them - a different denominator, printed separately everywhere it appears, because
the two counts share their rows and not their columns.

---

## The families
`);

for (const Entry of Reference.Reference) {
	const Unasked = Reference.Unasked.find(
		(Row) => Row.band === Entry.band,
	) ?? {
		conditions: [],
		cells: 0,
	};

	Out.push(`### \`${Entry.index}\` ${Entry.band}

${Line("For", Entry.for)}

${Line("Read for", Entry.read)}

${Line("Its boundary", Entry.gap)}

${Table(
	["FIGURE", "VALUE"],
	[
		["COMPONENTS", String(Entry.figures.components)],
		["COLUMNS", String(Entry.figures.columns)],
		["ITS OWN MATRIX", `${Entry.figures.cells} CELLS`],
		["BUILT", String(Entry.figures.built)],
		["NOT APPLICABLE", String(Entry.figures.reasons)],
		[
			"AGAINST THE SPINE",
			`${Entry.figures.spine.built} BUILT / ${Entry.figures.spine.reasons} N/A / ${Entry.figures.spine.unasked} UNASKED OF ${Entry.figures.spine.of}`,
		],
		[
			"LIVE ROWS",
			`${Entry.figures.specimens} IN ${Entry.figures.groups} GROUPS`,
		],
		["PROHIBITIONS", String(Entry.figures.laws)],
		["BEHAVIOURS", String(Entry.figures.changes)],
		["SOURCE", Entry.source],
	],
)}

#### Its slots - the parts a page may mount

${Table(
	[
		"PART",
		"FILE",
		"WHAT IT IS",
		`BUILT (OF ${Entry.figures.spine.of} SPINE CONDITIONS)`,
	],
	Entry.slots.map((Slot) => [
		Slot.name,
		Code(Slot.file),
		Slot.note,
		`${Slot.built} OF ${Slot.of}`,
	]),
)}

#### Its states - the conditions it is asked

${Table(
	["STATE", "ASKS", "BUILT IN THE FAMILY"],
	Entry.states.map((Column) => [
		Column.label,
		Column.ask,
		`${Column.built} OF ${Column.of}`,
	]),
)}

#### Its combinations - the shapes and contexts it is composed at

${Table(
	["COMBINATION", "GROUP", "ASKS", "BUILT IN THE FAMILY"],
	Entry.combinations.map((Column) => [
		Column.label,
		Column.group,
		Column.ask,
		`${Column.built} OF ${Column.of}`,
	]),
)}

#### What it may never be

The strongest ${Entry.strongest.length} of the ${Entry.figures.laws} sentences this
family's matrix uses to mark a combination impossible. The numbering is the
family's, and the matrix below references it cell by cell.

${Entry.strongest
	.map((Law, Position) => {
		const Index = Entry.laws.indexOf(Law) + 1;

		return `${Index}. **${Law.count} cell${Law.count === 1 ? "" : "s"}.** ${Text(Law.text)}

   ${Code(Law.cells.join(" / "))}`;
	})
	.join("\n\n")}

#### The row that proves it

${
	Entry.proof === undefined
		? `**◎ PROOF: UNAVAILABLE.** The reference names the mark ${Code(Entry.proofAbsent)} as this family's proof, and the family's \`Specimens\` no longer carries it - so the pointer is stated rather than resolved, because a proof that names a row nobody prints is a claim with no source.`
		: `| MARK | STATE | PART |
| --- | --- | --- |
| \`${Entry.proof.mark}\` | ${Cell(Entry.proof.state)} | ${Cell(Entry.proof.component)} |

**When it is right.** ${Text(Entry.proof.when)}

**Why this row.** ${Text(Entry.proof.why)}

**See it.** \`/Specimen/States\` - the family's row on the states gallery; \`${Entry.href}\` - the family's own matrix.`
}

#### Its matrix - ${Entry.figures.components} rows × ${Entry.figures.columns} columns

\`▪\` is a combination the family renders. \`N/A[n]\` is one it cannot, and \`n\` is
the number of the sentence under the table. Every cell is read through the
family's own \`MatrixCell\`, so this table and the family's matrix cannot
disagree.

${Table(
	["PART", ...Entry.matrix.columns.map((Column) => Column.label)],
	Entry.matrix.rows.map((Row) => [
		Row.name,
		...Row.cells.map((CellValue) => Mark(CellValue)),
	]),
)}

Every sentence the matrix uses, numbered as the cells reference them:

${Entry.laws
	.map(
		(Law, Position) =>
			`**${Position + 1}.** ${Law.count} cell${Law.count === 1 ? "" : "s"} - ${Text(Law.text)} ${Code(Law.cells.join(" / "))}`,
	)
	.join("\n\n")}

#### What the exploration changed

${
	Entry.changes.length === 0
		? `**◎ IMPROVEMENTS: UNAVAILABLE.** \`${Entry.source}\` carries no \`Improvements\` export: its family was printed before the convention existed, so the behaviours its matrix produced are recorded as the notes on the cells it built - and those notes are in the matrix above. The absence is stated rather than filled, because a behaviour with no cell behind it is a preference.`
		: Entry.changes
				.map(
					(
						Change,
						Position,
					) => `${Position + 1}. **${Change.component}** - from \`${Change.from}\`

   **Found.** ${Text(Change.found)}

   **Built.** ${Text(Change.built)}`,
				)
				.join("\n\n")
}

#### What its matrix does not ask

${
	Unasked.conditions.length === 0
		? "Nothing: this family's matrix puts a column against every condition the spine names - the only answer that needs no sentence under it."
		: `${Unasked.conditions.length} conditions, ${Unasked.cells} cells unanswered - \`${Unasked.conditions.join("`, `")}\`. The family's matrix has no column for these, and \`/Specimen/States\` §THE UNASKED prints the sentence that says why.`
}

#### Its live rows

${Entry.groups
	.map((Group) => `- **${Group.label}** - ${Text(Group.note)}`)
	.join("\n")}

---
`);
}

Out.push(`## The register - what this document counted

${Table(
	["FIGURE", "VALUE"],
	Reference.Register.map((Row) => [Row.key.replace(/:$/, ""), Row.value]),
)}

The ten files it was counted from:

${Table(
	["FAMILY", "SOURCE", "COMPONENTS", "COLUMNS", "CELLS", "BUILT", "N/A"],
	Reference.Reference.map((Entry) => [
		Entry.band,
		Code(Entry.source),
		String(Entry.figures.components),
		String(Entry.figures.columns),
		String(Entry.figures.cells),
		String(Entry.figures.built),
		String(Entry.figures.reasons),
	]),
)}

### What this document could not prove

- **It cannot tell you whether a component is *good*.** It can tell you what a
  family claims, what it survives and what it forbids; taste is not in the
  tables.
- **Three families carry no recorded behaviours.** \`Field.ts\`, \`Overlay.ts\` and
  \`Display.ts\` predate the \`Improvements\` convention, so their entries state the
  absence instead of inventing an entry. Their matrix notes are the evidence, and
  the notes print above.
- **The proof row is chosen, not derived.** The mark is named in
  \`Reference.ts\` and resolved against the family's \`Specimens\`, so it cannot
  point at a row that no longer exists - but *why* that row proves the family is
  a judgement, and it is written down as one.
- **The matrices are the families' own.** A condition the spine names and a
  family never asks appears here as a hole, not as a cell. The spine's count and
  the families' count are printed separately for that reason.

### Regenerating

\`\`\`sh
node Maintain/Script/Reference.mjs
\`\`\`

The script reads \`Source/Content/Specimen/Reference.ts\`, which reads the ten
family modules. Nothing else needs to change when a family does.
`);

await mkdir(dirname(Target), { recursive: true });

/** The document, as the model prints it. */
let Markdown = `${Out.join("\n")}\n`;

/**
 * Format through the repository's own Prettier, when it is installed.
 *
 * `dum Format` runs Prettier over the tree, and a generated document that
 * Prettier would reformat is a document that changes every time somebody runs
 * the formatter - a diff with no author. So the generator asks for the same
 * config the repository uses and writes what Prettier would have written. If
 * Prettier is not installed the document is still complete and still correct;
 * it is only wider.
 */
let Formatted = false;

try {
	const { format, resolveConfig } = await import("prettier");

	const Config = (await resolveConfig(Target)) ?? {};

	Markdown = await format(Markdown, { ...Config, parser: "markdown" });

	Formatted = true;
} catch {
	Formatted = false;
}

await writeFile(Target, Markdown, "utf8");

console.log(
	`Reference: wrote ${Target} - ${Reference.EntryCount} entries, ${Reference.SlotCount} slots, ${Reference.MatrixCells} cells, ${Reference.LawCount} prohibitions${Formatted ? ", formatted with the repository's Prettier" : " (Prettier not installed: unformatted)"}.`,
);
